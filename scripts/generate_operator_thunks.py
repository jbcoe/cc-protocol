def render_operator_block(operator_definition: OperatorDefinition) -> str:
    """Render the thunk and overload-set specializations for one operator."""
    meta_enum_name = operator_definition.meta_enum_name
    symbol = operator_definition.symbol
    if operator_definition.unary_only:
        template_parameters = (
            "typename R, bool IsNoexcept, typename ProtocolType,\n"
            "          typename Vtable, std::meta::info Member,\n"
            "          member_qualifiers MemberQualifiers"
        )
        function_pointer_type = "R (*)() noexcept(IsNoexcept)"
        parameter_list = ""
        forwarded_arguments = ""
    else:
        template_parameters = (
            "typename R, typename... Args, bool IsNoexcept, typename ProtocolType,\n"
            "          typename Vtable, std::meta::info Member,\n"
            "          member_qualifiers MemberQualifiers"
        )
        function_pointer_type = "R (*)(Args...) noexcept(IsNoexcept)"
        parameter_list = "Args... args"
        forwarded_arguments = ",\n        std::forward<Args>(args)..."

    using_operator_name = f"operator{symbol} " if symbol == "," else f"operator{symbol}"

    return f"""\
// operator{symbol}
template <{template_parameters}>
struct xyz_protocol_operator_thunk<
    std::meta::operators::{meta_enum_name},
    {function_pointer_type},
    ProtocolType, Vtable, Member, MemberQualifiers> {{
  R operator{symbol}({parameter_list}) noexcept(IsNoexcept)
    requires(MemberQualifiers == member_qualifiers::unqualified)
  {{
    auto* protocol_object = static_cast<ProtocolType*>(this);
    return call_through_vtable<Member, Vtable>(
        protocol_object, protocol_object->xyz_protocol_vtable_,
        protocol_object->xyz_protocol_erased_object(){forwarded_arguments});
  }}

  R operator{symbol}({parameter_list}) const noexcept(IsNoexcept)
    requires(MemberQualifiers == member_qualifiers::const_qualified)
  {{
    const auto* protocol_object = static_cast<const ProtocolType*>(this);
    return call_through_vtable<Member, Vtable>(
        protocol_object, protocol_object->xyz_protocol_vtable_,
        protocol_object->xyz_protocol_erased_object(){forwarded_arguments});
  }}

 protected:
  xyz_protocol_operator_thunk() = default;
  ~xyz_protocol_operator_thunk() = default;
  xyz_protocol_operator_thunk(const xyz_protocol_operator_thunk&) = default;
  xyz_protocol_operator_thunk(xyz_protocol_operator_thunk&&) = default;
  xyz_protocol_operator_thunk& operator=(const xyz_protocol_operator_thunk&) =
      default;
  xyz_protocol_operator_thunk& operator=(xyz_protocol_operator_thunk&&) =
      default;
}};

template <typename ProtocolType, typename Vtable, typename... OverloadSpecs>
struct xyz_protocol_operator_overload_set<
    std::meta::operators::{meta_enum_name}, ProtocolType, Vtable,
    OverloadSpecs...>
    : operator_thunk_t<OverloadSpecs, ProtocolType, Vtable>... {{
  using operator_thunk_t<OverloadSpecs, ProtocolType, Vtable>::{using_operator_name}...;

 protected:
  xyz_protocol_operator_overload_set() = default;
  ~xyz_protocol_operator_overload_set() = default;
  xyz_protocol_operator_overload_set(
      const xyz_protocol_operator_overload_set&) = default;
  xyz_protocol_operator_overload_set(xyz_protocol_operator_overload_set&&) =
      default;
  xyz_protocol_operator_overload_set& operator=(
      const xyz_protocol_operator_overload_set&) = default;
  xyz_protocol_operator_overload_set& operator=(
      xyz_protocol_operator_overload_set&&) = default;
}};
"""


def generate_header() -> str:
    """Return the full contents of xyz/detail/operator_thunks.hh."""
    sections = [HEADER_PROLOGUE]
    sections.extend(render_operator_block(operator) for operator in OPERATORS)
    sections.append(HEADER_EPILOGUE)
    return "\n".join(sections)


def main() -> None:
    """Write the generated operator thunks header to the requested output path."""
    argument_parser = argparse.ArgumentParser(
        description="Generate xyz/detail/operator_thunks.hh."
    )
    argument_parser.add_argument(
        "--output",
        type=Path,
        required=True,
        help="Output file path.",
    )
    parsed_arguments = argument_parser.parse_args()
    output_path: Path = parsed_arguments.output
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(generate_header(), encoding="utf-8")


if __name__ == "__main__":
    main()
